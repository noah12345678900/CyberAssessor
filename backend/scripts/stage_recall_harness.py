# ---------------------------------------------------------------------------
# Ground truth: title -> {control_id lower} from a completed assessor DB
# ---------------------------------------------------------------------------
def load_truth(truth_db: str) -> dict[str, set[str]]:
    con = sqlite3.connect(f"file:{truth_db}?mode=ro", uri=True)
    truth: dict[str, set[str]] = {}
    q = """
        select e.title, c.control_id
        from evidencetag t
        join evidence e on e.id = t.evidence_id
        join objective o on o.id = t.objective_id
        join control c on c.id = o.control_id_fk
        group by e.title, c.control_id
    """
    for title, cid in con.execute(q):
        if title:
            truth.setdefault(title, set()).add(cid.lower())
    con.close()
    return truth


# ---------------------------------------------------------------------------
# Catalog (cids + control_texts) — built with the SAME production functions the
# tagger uses (_all_objectives_by_control + _control_reference_text +
# _augment_control_text), so the harness scores against the IDENTICAL retrieval
# corpus production does. Also returns all_by_control for the folder lane.
# ---------------------------------------------------------------------------
def load_catalog(
    catalog_db: str, framework_id: int, augment: bool = True
) -> tuple[list[str], list[str], dict]:
    tmp = tempfile.mkdtemp(prefix="harness_cat_")
    dst = os.path.join(tmp, "cat.sqlite")
    sc = sqlite3.connect(f"file:{catalog_db}?mode=ro", uri=True)
    dc = sqlite3.connect(dst)
    sc.backup(dc)
    dc.close()
    sc.close()
    eng = create_engine(f"sqlite:///{dst}", connect_args={"check_same_thread": False})
    with Session(eng) as s:
        all_by_control = T._all_objectives_by_control(s, framework_id=framework_id)
        control_by_cid = T._controls_by_cid(s, framework_id=framework_id)
    eng.dispose()
    cids = sorted(all_by_control.keys())
    # EXACTLY mirror tagger._tag_via_llm's RETRIEVAL corpus build (the split:
    # _retrieval_reference_text = title+statement+objective, ODP-stripped, +gloss).
    # This is candidate-generation text; the judge uses clean normative text
    # separately (not exercised by the generation/cap stages measured here).
    if augment:
        control_texts = [
            T._augment_control_text(
                cid,
                T._retrieval_reference_text(control_by_cid.get(cid), all_by_control[cid]),
            )
            for cid in cids
        ]
    else:
        control_texts = [
            T._retrieval_reference_text(control_by_cid.get(cid), all_by_control[cid])
            for cid in cids
        ]
    return cids, control_texts, all_by_control


