"""Stage-by-stage candidate-recall harness for the evidence tagger.

WHY THIS EXISTS
---------------
The tagger's recall failures live at DIFFERENT pipeline stages, and a single
final-tag number can't tell them apart. A control the doc should tag to can be
lost because:

  * GENERATION  — no lane ever nominated it (terse enhancement text, vocab
                  mismatch like "multi-factor" vs "multifactor").
  * FUSION+CAP  — a lane DID nominate it, but RRF ranked it past _RAG_FUSED_CAP
                  and it was truncated before the judge saw it.
  * JUDGE       — it reached the judge but was scored < accept threshold.

This harness runs the REAL tagger internals against a REAL evidence corpus and
reports recall at each stage, measured against a ground-truth control set (the
known-good Claude baseline). Every candidate-generation fix (folder-truncation,
char n-grams, must-judge cap-exemption, enhancement expansion, parent-aware
retrieval, section-level retrieval) gets a before/after number here so we can
prove recall went UP and precision did NOT go down — instead of guessing.

It is a MEASUREMENT TOOL, not a CI gate (mirrors score_recall.py /
scripts/eval_workbook.py). No LLM judge is invoked by default (the generation
and cap stages are LLM-free and deterministic given a fixed HyDE prose); pass
--with-judge to also measure the judged stage against a live client.

GROUND TRUTH
------------
``--truth-db`` points at a completed assessor.sqlite whose evidencetag rows are
treated as the oracle: for each evidence title, the set of distinct control_ids
it was tagged to. The default is the Claude baseline in the recycle bin. The
harness re-runs candidate generation for the SAME documents (matched by title →
on-disk file under --evidence-root) and reports, per doc and micro-averaged:

    truth              controls the baseline tagged (oracle)
    gen_recall         fraction of truth generated by ANY lane (generation ceiling)
    cap_recall         fraction of truth surviving the RRF top-15 cap
    (judge_recall)     fraction of truth the judge accepts   [--with-judge]

USAGE
-----
    cd backend
    uv run --no-sync python scripts/stage_recall_harness.py \
        --evidence-root "C:/.../eMASS_BoE_Upload+Stigs_07112026" \
        --framework-id 2 \
        [--truth-db "C:/$Recycle.Bin/.../assessor.sqlite"] \
        [--catalog-db ~/.cybersecurity-assessor/assessor.sqlite] \
        [--with-judge] [--json out.json] [--only-broad N]

Deterministic stages (gen/cap) need no network. --with-judge and the HyDE lane
need a live OpenAI client (resolved from config), matching production.
"""

