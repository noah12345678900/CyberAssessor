def _norm(x: str) -> str:
    return re.sub(r"[^a-z0-9]", "", x.lower())


def index_evidence_files(root: str) -> list[str]:
    return [
        f
        for f in glob.glob(root + "/**/*", recursive=True)
        if f.lower().endswith((".docx", ".pdf"))
    ]


def find_file(title: str, files: list[str]) -> str | None:
    """Collision-SAFE title->file match. Returns a file only when EXACTLY ONE
    candidate matches; ambiguous (>1) or no match returns None (skipped, not
    silently scored against the wrong doc).

    Truth-DB titles are stored TRUNCATED to 40 chars (title[:40]), which cuts
    long BoE names mid-word (e.g. "..._Account_Manageme") so neither string
    contains the other AND a fixed 16-char prefix can collide across sibling
    USD-numbered docs. So the match is: (a) full containment either way, OR
    (b) a LONG shared normalized prefix (>=24 chars) — long enough that the
    USD number + several title words align, short enough to survive the 40-char
    truncation. Collision safety is preserved by the exactly-one-hit rule."""
    # Strip the eMASS "NN.x.XX_" ordering prefix from BOTH sides — the truth-DB
    # title often carries it (01.o.AC_USD...) while the filename does too; if we
    # only strip the filename the normalized prefixes never align.
    _pfx = re.compile(r"^\d+\.[a-z]\.[A-Za-z]{2}_")
    tn = _norm(_pfx.sub("", title))
    hits: list[str] = []
    for f in files:
        stem = _pfx.sub("", os.path.splitext(os.path.basename(f))[0])
        sn = _norm(stem)
        if not sn:
            continue
        # longest common prefix length
        lcp = 0
        for a, b in zip(tn, sn):
            if a != b:
                break
            lcp += 1
        if (
            (len(sn) >= 8 and sn in tn)
            or (len(tn) >= 8 and tn in sn)
            or lcp >= 24
        ):
            hits.append(f)
    if len(hits) == 1:
        return hits[0]
    return None  # 0 or ambiguous -> skip (never guess)


def read_text(f: str) -> str:
    """Extract text via the app's OWN extractor so the harness sees exactly what
    the tagger sees (pdfplumber/pypdf for PDF, python-docx for docx). Falls back
    to a raw docx-xml strip if the extractor errors."""
    try:
        from cybersecurity_assessor.evidence.extractors import extract_stream

        with open(f, "rb") as stream:
            doc = extract_stream(stream, os.path.basename(f))
        return (doc.text or "").strip()
    except Exception:
        if f.lower().endswith(".docx"):
            try:
                with zipfile.ZipFile(f) as z:
                    xml = z.read("word/document.xml").decode("utf-8", "ignore")
                return re.sub(r"\s+", " ", re.sub(r"<[^>]+>", " ", xml)).strip()
            except Exception:
                return ""
        return ""


